// Bundles the helper into one file and puts it, with the Windows installer,
// where the web app serves it (/helper/...), so the Settings page can link to
// it and the helper can update itself from the app.
import { build } from 'esbuild';
import { copyFileSync, mkdirSync } from 'node:fs';

const out = '../web/public/helper';
mkdirSync(out, { recursive: true });
await build({
  entryPoints: ['src/entry.ts'],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  outfile: `${out}/newsletter-helper.mjs`,
  banner: { js: '// Newsletter app PC helper. Generated by apps/helper/build.mjs; do not edit.' },
});
copyFileSync('windows/install-helper.ps1', `${out}/install-helper.ps1`);
console.log(`helper bundled into ${out}`);
